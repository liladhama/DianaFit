// Генерация 5 приемов пищи с учетом типа диеты и целевых калорий
const mealTypes = [
  { type: 'Завтрак', ratio: 0.25 },
  { type: 'Перекус', ratio: 0.10 },
  { type: 'Обед', ratio: 0.30 },
  { type: 'Полдник', ratio: 0.15 },
  { type: 'Ужин', ratio: 0.20 }
];

const mealBases = {
  meat: [
    'Овсянка с курицей', 'Яйцо с тостом', 'Курица с рисом', 'Творог с медом', 'Говядина с овощами',
    'Салат с тунцом', 'Суп с мясом', 'Паста с курицей', 'Омлет с ветчиной', 'Запеченная рыба с картофелем'
  ],
  fish: [
    'Овсянка с семгой', 'Яйцо с тостом', 'Рыба с рисом', 'Творог с медом', 'Салат с тунцом',
    'Суп с рыбой', 'Паста с семгой', 'Омлет с овощами', 'Запеченная рыба с картофелем', 'Салат с креветками'
  ],
  vegetarian: [
    'Овсянка с фруктами', 'Яйцо с тостом', 'Рис с овощами', 'Творог с медом', 'Салат с фасолью',
    'Суп овощной', 'Паста с овощами', 'Омлет с сыром', 'Запеченные овощи', 'Салат с орехами'
  ],
  vegan: [
    'Овсянка с орехами', 'Смузи с бананом', 'Рис с овощами', 'Салат с фасолью', 'Суп овощной',
    'Паста с овощами', 'Запеченные овощи', 'Салат с нутом', 'Суп с чечевицей', 'Салат с тофу'
  ]
};

export function generateMealsForDay(dietType = 'meat', targetCalories = 1800) {
  const base = mealBases[dietType] || mealBases['meat'];
  // Перемешиваем блюда
  const shuffled = [...base].sort(() => 0.5 - Math.random());
  // Распределяем калории по типам
  return mealTypes.map((meal, idx) => ({
    type: meal.type,
    menu: shuffled[idx % shuffled.length],
    calories: Math.round(targetCalories * meal.ratio)
  }));
}
